CREATE OR REPLACE VIEW VW_PRODUTOS_VENCIMENTOS AS 
SELECT 
	PRO_NOME AS "NOME DO PRODUTO",
    PRO_PRECO AS "PREÇO DO PRODUTO",
    PRO_QUANTIDADE AS "QUANTIDADES DO PRODUTO",
    PRO_DATA_VALIDADE AS "DATA VALIDADE",
    DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) AS "DATA DE VENCIMENTO"
FROM PRODUTO
WHERE  DATEDIFF(PRO_DATA_VALIDADE, CURDATE()) <= 15;
SELECT * FROM VW_PRODUTOS_VENCIMENTOS;

