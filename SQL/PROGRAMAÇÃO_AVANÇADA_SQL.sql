VIEW: SÃO PESEUDO-TABELAS QUE GRAVAM SQL GRANDES PARA SEREM EXECUTADOS EM DIVERSAS PARTES DO CODIGO, SEM PRECISAR REESCREVER O SELECT. */

-- CIAR UM VIEW PARA RETORNAR OS CUNCIONARIOS E SEUS SUPERMERCADOS 
CREATE VIEW VW_FUNCIONARIOS_SUPERMERCADOS AS 
SELECT 
	F.FUN_CPF AS "CPF",
	F.FUN_DATA_NASCIMENTO AS "DATA DE NASCIMENTO",
	F.FUN_NOME AS "NOME",
	F.FUN_TELEFONE AS "TELEFONE",
	F.FUN_EMAIL AS "E-MAIL",
	F.FUN_CARTEIRA_TRABALHO AS "CARTEIRA DE TRABALHO",
	F.FUN_BANCO_AGENCIA AS "AGENCIA DO BANCO",
	F.FUN_BANCO_CONTA AS "CONTA DO BANCO",
	F.FUN_DATA_ADMISSAO AS "DATA DE ADMISSÃO",
	F.FUN_JORNADA_TRABALHO AS "JORNADA DE TRABALHO",
	S.SUP_RAZAO_SOCIAL AS "SUPERMERCADO QUE TRABALHA"
FROM FUNCIONARIO F
JOIN SUPERMERCADO S 
ON (S.SUP_CNPJ = F.FK_SUP_CNPJ);

SELECT * FROM  VW_FUNCIONARIOS_SUPERMERCADOS;
SELECT * FROM  VW_FUNCIONARIOS_SUPERMERCADOS;

SELECT * 
FROM  VW_FUNCIONARIOS_SUPERMERCADOS
WHERE UPPER(NOME) LIKE '%RAFAEL';


