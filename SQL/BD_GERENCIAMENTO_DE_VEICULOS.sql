CREATE DATABASE IF NOT EXISTS BD_VEICULOS;
USE BD_VEICULOS;

CREATE TABLE IF NOT EXISTS USUARIOS(
    USU_CODIGO INT AUTO_INCREMENT,
    USU_NOME VARCHAR(100) NOT NULL,
    USU_EMAIL VARCHAR(100) NOT NULL UNIQUE,
    USU_SENHA VARCHAR(255) NOT NULL,
    USU_CREATED_AT TIMESTAMP NULL,
    USU_UPDATED_AT TIMESTAMP NULL,
    PRIMARY KEY(USU_CODIGO)
);

CREATE TABLE IF NOT EXISTS CLIENTES(
    CLI_CODIGO INT AUTO_INCREMENT,
    CLI_NOME VARCHAR(100) NOT NULL,
    CLI_CPF VARCHAR(255) NOT NULL,
    CLI_TELEFONE VARCHAR(20),
    CLI_EMAIL VARCHAR(100),
    CLI_CREATED_AT TIMESTAMP NULL,
    PRIMARY KEY(CLI_CODIGO)
);

CREATE TABLE IF NOT EXISTS VEICULOS(
    VEI_CODIGO INT AUTO_INCREMENT,
    VEI_PLACA VARCHAR(100) NOT NULL,
    VEI_MARCA VARCHAR(50) NOT NULL,
    VEI_MODELO VARCHAR(50),
    CLI_CODIGO INT NOT NULL,
    VEI_CREATED_AT TIMESTAMP NULL,
    PRIMARY KEY(VEI_CODIGO),
    FOREIGN KEY(CLI_CODIGO)
        REFERENCES CLIENTES(CLI_CODIGO)
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS(
    AGE_CODIGO INT AUTO_INCREMENT,
    AGE_DATA DATE NOT NULL,
    AGE_HORA TIME NOT NULL,
    AGE_DESCRICAO VARCHAR(255),
    VEI_CODIGO INT NOT NULL,
    AGE_CREATED_AT TIMESTAMP NULL,
    PRIMARY KEY(AGE_CODIGO),
    FOREIGN KEY(VEI_CODIGO)
        REFERENCES VEICULOS(VEI_CODIGO)
);

