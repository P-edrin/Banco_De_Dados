SELECT
    C.CLI_NOME,
    V.VEI_PLACA,
    V.VEI_MARCA,
    V.VEI_MODELO,
    A.AGE_DATA,
    A.AGE_HORA,
    A.AGE_DESCRICAO
FROM CLIENTES C
LEFT JOIN VEICULOS V
    ON C.CLI_CODIGO = V.CLI_CODIGO
LEFT JOIN AGENDAMENTOS A
    ON V.VEI_CODIGO = A.VEI_CODIGO;

SELECT
    C.CLI_CODIGO,
    C.CLI_NOME,
    COUNT(V.VEI_CODIGO) AS QUANTIDADE_CARROS
FROM CLIENTES C
LEFT JOIN VEICULOS V
    ON C.CLI_CODIGO = V.CLI_CODIGO
GROUP BY
    C.CLI_CODIGO,
    C.CLI_NOME;

SELECT
    V.VEI_CODIGO,
    V.VEI_PLACA,
    V.VEI_MARCA,
    V.VEI_MODELO,
    COUNT(A.AGE_CODIGO) AS QUANTIDADE_AGENDAMENTOS
FROM VEICULOS V
LEFT JOIN AGENDAMENTOS A
    ON V.VEI_CODIGO = A.VEI_CODIGO
GROUP BY
    V.VEI_CODIGO,
    V.VEI_PLACA,
    V.VEI_MARCA,
    V.VEI_MODELO;

SELECT
    C.CLI_CODIGO,
    C.CLI_NOME,
    COUNT(A.AGE_CODIGO) AS QUANTIDADE_AGENDAMENTOS
